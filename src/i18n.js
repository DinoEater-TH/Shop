export const LANGUAGES = [
  { code: 'th', label: 'TH' },
  { code: 'en', label: 'EN' },
  { code: 'zh', label: '中文' }
]

let _lang = typeof localStorage !== 'undefined' ? (localStorage.getItem('dino-lang') || 'th') : 'th'
const listeners = new Set()
export function getLang() { return _lang }
export function setLang(code) {
  _lang = code
  if (typeof localStorage !== 'undefined') localStorage.setItem('dino-lang', code)
  listeners.forEach(fn => fn(code))
}
export function subscribeLang(fn) { listeners.add(fn); return () => listeners.delete(fn) }

export function useLang() {
  const [lang, setLangState] = useState(_lang)
  useEffect(() => subscribeLang(setLangState), [])
  return lang
}

