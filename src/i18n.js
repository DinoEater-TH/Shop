export function t(key, vars = {}) {
  const entry = DICT[key]
  const text = entry ? (entry[_lang] || key) : key
  return text.replace(/\{(\w+)\}/g, (_, k) => vars[k] != null ? vars[k] : `{${k}}`)
}

